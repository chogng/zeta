import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { basename, dirname, extname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { optimize } from "svgo";

const repositoryDirectory = resolve(import.meta.dirname, "../../..");
const desktopDirectory = resolve(repositoryDirectory, "desktop");
const iconDirectory = resolve(repositoryDirectory, "resources/icons");
const output = resolve(desktopDirectory, "generated/product-icons.ts");
const iconFilePattern = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*\.svg$/;
const unsafeSvgPattern = /<(?:script|foreignObject)\b|\son[a-z]+\s*=|(?:href|xlink:href)\s*=/i;

interface ProductIconOptions {
  readonly outputFile?: string;
  readonly sourceDirectory?: string;
  readonly writeSources?: boolean;
}

interface ProductIconReport {
  readonly count: number;
  readonly outputChanged: boolean;
  readonly sourceChanged: boolean;
}

interface ProductIconSourceUpdate {
  readonly content: string;
  readonly fileName: string;
  readonly path: string;
}

export async function syncProductIcons(options: ProductIconOptions = {}): Promise<ProductIconReport> {
  const sourceDirectory = options.sourceDirectory ?? iconDirectory;
  const outputFile = options.outputFile ?? output;
  const writeSources = options.writeSources ?? true;
  const compilation = await compileProductIcons(sourceDirectory);
  if (writeSources) {
    await Promise.all(compilation.sourceUpdates.map((update) => writeFile(update.path, update.content, "utf8")));
  }
  const outputChanged = await writeFileIfChanged(outputFile, compilation.generated);
  return { count: compilation.count, outputChanged, sourceChanged: writeSources && compilation.sourceUpdates.length > 0 };
}

export async function checkProductIcons(options: Pick<ProductIconOptions, "sourceDirectory"> = {}): Promise<{ readonly count: number }> {
  const sourceDirectory = options.sourceDirectory ?? iconDirectory;
  const compilation = await compileProductIcons(sourceDirectory);
  if (compilation.sourceUpdates.length > 0) {
    const fileNames = compilation.sourceUpdates.map((update) => update.fileName);
    throw new Error(`${fileNames.length} product icon(s) require synchronization: ${fileNames.join(", ")}. Run 'pnpm icons:sync'.`);
  }
  return { count: compilation.count };
}

async function compileProductIcons(sourceDirectory: string): Promise<{ readonly count: number; readonly generated: string; readonly sourceUpdates: ProductIconSourceUpdate[] }> {
  const iconFiles = (await readdir(sourceDirectory, { withFileTypes: true }))
    .filter((entry) => entry.isFile() && extname(entry.name) === ".svg")
    .map((entry) => entry.name)
    .sort();
  if (iconFiles.length === 0) {
    throw new Error(`No product icons found in ${sourceDirectory}`);
  }

  const exports: string[] = [];
  const exportNames = new Set<string>();
  const sourceUpdates: ProductIconSourceUpdate[] = [];
  for (const fileName of iconFiles) {
    if (!iconFilePattern.test(fileName)) {
      throw new Error(`Invalid product icon filename '${fileName}'`);
    }
    const sourcePath = resolve(sourceDirectory, fileName);
    const source = await readFile(sourcePath, "utf8");
    const svg = source.trim();
    validateSvg(fileName, svg);
    const optimizedSvg = optimizeSvg(fileName, svg);
    validateSvg(fileName, optimizedSvg);

    const canonicalSource = `${optimizedSvg}\n`;
    if (source !== canonicalSource) {
      sourceUpdates.push({ content: canonicalSource, fileName, path: sourcePath });
    }

    const exportName = iconExportName(fileName);
    if (exportNames.has(exportName)) {
      throw new Error(`Duplicate generated product icon export '${exportName}'`);
    }
    exportNames.add(exportName);
    const bindingName = `icon${exportName[0].toUpperCase()}${exportName.slice(1)}`;
    exports.push(`const ${bindingName} = () => ${JSON.stringify(optimizedSvg)};`);
    exports.push(`export { ${bindingName} as ${exportName} };`);
  }

  const generated = [
    "// Generated from resources/icons by build/desktop/resources/syncProductIcons.ts.",
    "// Do not edit this file directly.",
    "",
    ...exports,
    "",
  ].join("\n");
  return { count: iconFiles.length, generated, sourceUpdates };
}

function iconExportName(fileName: string): string {
  const words = basename(fileName, ".svg").split("-");
  return `${words[0]}${words.slice(1).map((word) => `${word[0].toUpperCase()}${word.slice(1)}`).join("")}`;
}

function optimizeSvg(fileName: string, svg: string): string {
  const iconName = basename(fileName, ".svg");
  return optimize(svg, {
    path: fileName,
    multipass: true,
    plugins: [
      "preset-default",
      {
        name: "prefixIds",
        params: {
          delim: "-",
          prefix: `zeta-${iconName}`,
        },
      },
      "removeDimensions",
    ],
  }).data.trim();
}

function validateSvg(fileName: string, svg: string): void {
  if (!svg.startsWith("<svg") || !svg.endsWith("</svg>")) {
    throw new Error(`Product icon '${fileName}' must contain one SVG root`);
  }
  if ((svg.match(/<svg\b/g) ?? []).length !== 1 || (svg.match(/<\/svg>/g) ?? []).length !== 1) {
    throw new Error(`Product icon '${fileName}' must contain exactly one SVG root`);
  }
  if (unsafeSvgPattern.test(svg)) {
    throw new Error(`Product icon '${fileName}' contains unsupported active or external content`);
  }
}

async function writeFileIfChanged(path: string, content: string): Promise<boolean> {
  try {
    if (await readFile(path, "utf8") === content) {
      return false;
    }
  } catch (error: unknown) {
    if (!(error instanceof Error && "code" in error && error.code === "ENOENT")) {
      throw error;
    }
  }
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, content, "utf8");
  return true;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const argumentsList = process.argv.slice(2);
  if (argumentsList.length > 1 || (argumentsList.length === 1 && argumentsList[0] !== "--check")) {
    throw new Error(`Expected --check or no arguments; received ${argumentsList.join(" ")}`);
  }
  if (argumentsList[0] === "--check") {
    const report = await checkProductIcons();
    console.log(`Validated ${report.count} synchronized product icons.`);
  } else {
    const report = await syncProductIcons();
    const status = report.outputChanged || report.sourceChanged ? "Synchronized" : "Already synchronized";
    console.log(`${status} ${report.count} product icons.`);
  }
}
