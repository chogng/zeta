import { watch } from "node:fs";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { basename, dirname, extname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { optimize } from "svgo";

const desktopDirectory = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repositoryDirectory = resolve(desktopDirectory, "..");
const iconDirectory = resolve(repositoryDirectory, "resources/icons");
const output = resolve(desktopDirectory, "generated/product-icons.ts");
const iconFilePattern = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*\.svg$/;
const unsafeSvgPattern = /<(?:script|foreignObject)\b|\son[a-z]+\s*=|(?:href|xlink:href)\s*=/i;

export async function syncProductIcons(options = {}) {
  const sourceDirectory = options.sourceDirectory ?? iconDirectory;
  const outputFile = options.outputFile ?? output;
  const mode = options.mode ?? "generate";
  if (!["check", "generate", "optimize"].includes(mode)) {
    throw new Error(`Unknown product icon mode '${mode}'`);
  }

  const iconFiles = (await readdir(sourceDirectory, { withFileTypes: true }))
    .filter((entry) => entry.isFile() && extname(entry.name) === ".svg")
    .map((entry) => entry.name)
    .sort();
  if (iconFiles.length === 0) {
    throw new Error(`No product icons found in ${sourceDirectory}`);
  }

  const exports = [];
  const exportNames = new Set();
  const unoptimized = [];
  const rewrites = [];
  let sourceBytes = 0;
  let optimizedBytes = 0;
  for (const fileName of iconFiles) {
    if (!iconFilePattern.test(fileName)) {
      throw new Error(`Invalid product icon filename '${fileName}'`);
    }
    const sourcePath = resolve(sourceDirectory, fileName);
    const source = await readFile(sourcePath, "utf8");
    const svg = source.trim();
    validateSvg(fileName, svg);
    const optimizedSvg = optimizeSvg(fileName, svg);
    validateSvg(fileName, optimizedSvg);
    sourceBytes += Buffer.byteLength(source);
    optimizedBytes += Buffer.byteLength(optimizedSvg);

    const canonicalSource = `${optimizedSvg}\n`;
    if (source !== canonicalSource) {
      unoptimized.push(fileName);
      if (mode === "optimize") {
        rewrites.push([sourcePath, canonicalSource]);
      }
    }

    const exportName = iconExportName(fileName);
    if (exportNames.has(exportName)) {
      throw new Error(`Duplicate generated product icon export '${exportName}'`);
    }
    exportNames.add(exportName);
    const bindingName = `icon${exportName[0].toUpperCase()}${exportName.slice(1)}`;
    exports.push(`const ${bindingName} = () => ${JSON.stringify(optimizedSvg)};`);
    exports.push(`export { ${bindingName} as ${exportName} };`);
  }

  if (mode === "check") {
    if (unoptimized.length > 0) {
      throw new Error(`${unoptimized.length} product icon(s) require optimization: ${unoptimized.join(", ")}. Run 'pnpm icons:optimize'.`);
    }
    return { count: iconFiles.length, optimizedBytes, sourceBytes, unoptimized };
  }
  await Promise.all(rewrites.map(([sourcePath, canonicalSource]) => writeFile(sourcePath, canonicalSource, "utf8")));

  const generated = [
    "// Generated from resources/icons by scripts/sync-product-icons.mjs.",
    "// Do not edit this file directly.",
    "",
    ...exports,
    "",
  ].join("\n");
  await mkdir(dirname(outputFile), { recursive: true });
  await writeFile(outputFile, generated, "utf8");
  return { count: iconFiles.length, optimizedBytes, sourceBytes, unoptimized };
}

export async function watchProductIcons() {
  await logGeneration(await syncProductIcons());
  console.log(`Watching ${iconDirectory}`);
  let timer;
  let pending = Promise.resolve();
  const watcher = watch(iconDirectory, (_event, fileName) => {
    if (fileName && extname(fileName) !== ".svg") {
      return;
    }
    clearTimeout(timer);
    timer = setTimeout(() => {
      pending = pending
        .then(() => syncProductIcons())
        .then(logGeneration)
        .catch((error) => console.error(error instanceof Error ? error.message : error));
    }, 50);
  });
  await new Promise((resolvePromise, reject) => {
    watcher.on("error", reject);
    for (const signal of ["SIGINT", "SIGTERM"]) {
      process.once(signal, () => {
        clearTimeout(timer);
        watcher.close();
        resolvePromise();
      });
    }
  });
  await pending;
}

function iconExportName(fileName) {
  const words = basename(fileName, ".svg").split("-");
  return `${words[0]}${words.slice(1).map((word) => `${word[0].toUpperCase()}${word.slice(1)}`).join("")}`;
}

function optimizeSvg(fileName, svg) {
  const iconName = basename(fileName, ".svg");
  return optimize(svg, {
    path: fileName,
    multipass: true,
    plugins: [
      "preset-default",
      {
        name: "prefixIds",
        params: {
          delim: "-",
          prefix: `zeta-${iconName}`,
        },
      },
      "removeDimensions",
    ],
  }).data.trim();
}

function validateSvg(fileName, svg) {
  if (!svg.startsWith("<svg") || !svg.endsWith("</svg>")) {
    throw new Error(`Product icon '${fileName}' must contain one SVG root`);
  }
  if ((svg.match(/<svg\b/g) ?? []).length !== 1 || (svg.match(/<\/svg>/g) ?? []).length !== 1) {
    throw new Error(`Product icon '${fileName}' must contain exactly one SVG root`);
  }
  if (unsafeSvgPattern.test(svg)) {
    throw new Error(`Product icon '${fileName}' contains unsupported active or external content`);
  }
}

function logGeneration(report) {
  const savedBytes = report.sourceBytes - report.optimizedBytes;
  const saved = report.sourceBytes === 0 ? 0 : Math.round((1 - report.optimizedBytes / report.sourceBytes) * 100);
  const optimization = savedBytes > 0 ? `; removed ${savedBytes} source bytes (${saved}%)` : "";
  console.log(`Generated ${report.count} product icons (${report.optimizedBytes} optimized SVG bytes${optimization}).`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const argumentsSet = new Set(process.argv.slice(2));
  const knownArguments = new Set(["--check", "--optimize", "--watch"]);
  const unknownArguments = [...argumentsSet].filter((argument) => !knownArguments.has(argument));
  if (unknownArguments.length > 0 || argumentsSet.size > 1) {
    throw new Error(`Expected one of --check, --optimize, or --watch; received ${process.argv.slice(2).join(" ")}`);
  }
  if (argumentsSet.has("--watch")) {
    await watchProductIcons();
  } else {
    const mode = argumentsSet.has("--check") ? "check" : argumentsSet.has("--optimize") ? "optimize" : "generate";
    const report = await syncProductIcons({ mode });
    if (mode === "check") {
      console.log(`Validated ${report.count} optimized product icons (${report.optimizedBytes} bytes).`);
    } else {
      await logGeneration(report);
    }
  }
}
