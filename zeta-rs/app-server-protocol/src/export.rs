#[allow(dead_code)]
#[derive(JsonSchema)]
#[schemars(title = "Zeta App Server Protocol")]
#[serde(rename_all = "camelCase")]
struct ProtocolSchema {
    listen_info: AppServerListenInfo,
    client_request: JsonRpcRequest<ClientRequestSchema>,
    client_response: JsonRpcResponse<ClientResultSchema, AppServerError>,
    host_request: JsonRpcRequest<HostRequestSchema>,
    host_response: JsonRpcResponse<HostResultSchema, JsonRpcError>,
    server_notification: JsonRpcNotification<ServerNotificationSchema>,
    error_response: JsonRpcFailure<AppServerError>,
}

pub fn typescript() -> String {
    assert_typescript_bindings_are_closed();
    let schema_hash = schema_hash();
    let mut output = format!(
        "// Generated by `zeta-app-server-protocol generate_protocol`. Do not edit.\n\
         export const APP_SERVER_PROTOCOL_MAJOR = {} as const;\n\
         export const APP_SERVER_PROTOCOL_REVISION = {} as const;\n\
         export const APP_SERVER_CAPABILITY_VERSION = {} as const;\n\
         export const APP_SERVER_SCHEMA_HASH = {schema_hash:?} as const;\n\
         export type JsonRpcVersion = \"2.0\";\n\
         export type JsonRpcId = number | string | null;\n\
         export type JsonRpcRequest<P> = {{ jsonrpc: JsonRpcVersion; id: JsonRpcId; method: string; params: P }};\n\
         export type JsonRpcNotification<P> = {{ jsonrpc: JsonRpcVersion; method: string; params: P }};\n\
         export type JsonRpcSuccess<R> = {{ jsonrpc: JsonRpcVersion; id: JsonRpcId; result: R }};\n\
         export type JsonRpcFailure<E> = {{ jsonrpc: JsonRpcVersion; id: JsonRpcId; error: E }};\n\
         export type JsonRpcResponse<R, E> = JsonRpcSuccess<R> | JsonRpcFailure<E>;\n\
         export type JsonRpcError = {{ code: number; message: string; data: unknown }};\n",
        crate::protocol::initialize::APP_SERVER_PROTOCOL_MAJOR,
        crate::protocol::initialize::APP_SERVER_PROTOCOL_REVISION,
        crate::protocol::initialize::APP_SERVER_CAPABILITY_VERSION,
    );
    output.push_str("export ");
    output.push_str(&<AppServerListenInfo as ts_rs::TS>::decl(&Config::default()));
    output.push('\n');
    for binding in TYPESCRIPT_BINDINGS {
        output.push_str("export ");
        output.push_str(&binding.declaration());
        output.push('\n');
    }

    output.push_str("export interface AppServerNotificationMap {\n");
    for notification in SERVER_NOTIFICATIONS {
        output.push_str(&format!(
            "  {:?}: {};\n",
            notification.method,
            notification.params_type()
        ));
    }
    output.push_str(
        "}\n\
         export type AppServerNotificationMethod = keyof AppServerNotificationMap;\n\
         export type NotificationParams<M extends AppServerNotificationMethod> = AppServerNotificationMap[M];\n\
         export type ServerNotification = {\n\
           [M in AppServerNotificationMethod]: { method: M; params: NotificationParams<M> }\n\
         }[AppServerNotificationMethod];\n",
    );

    output.push_str(
        "export type AppServerWireNotification = {\n\
           [M in AppServerNotificationMethod]: { jsonrpc: JsonRpcVersion; method: M; params: NotificationParams<M> }\n\
         }[AppServerNotificationMethod];\n",
    );

    output.push_str("export interface AppServerRequestMap {\n");
    for method in CLIENT_METHODS {
        output.push_str(&format!(
            "  {:?}: {{ params: {}; response: {} }};\n",
            method.method,
            method.params_type(),
            method.result_type()
        ));
    }
    output.push_str(
        "}\n\
         export type AppServerMethod = keyof AppServerRequestMap;\n\
         export type MethodParams<M extends AppServerMethod> = AppServerRequestMap[M][\"params\"];\n\
         export type MethodResult<M extends AppServerMethod> = AppServerRequestMap[M][\"response\"];\n\
         export type AppServerRequest<M extends AppServerMethod> = JsonRpcRequest<MethodParams<M>> & { method: M };\n\
         export type AppServerResponse<M extends AppServerMethod> = JsonRpcResponse<MethodResult<M>, AppServerError>;\n\
         export type AppServerMethodDefinition<M extends AppServerMethod> = {\n\
           readonly method: M;\n\
           readonly __params?: MethodParams<M>;\n\
           readonly __result?: MethodResult<M>;\n\
         };\n\
         export const APP_SERVER_METHODS: { [M in AppServerMethod]: AppServerMethodDefinition<M> } = {\n",
    );
    for method in CLIENT_METHODS {
        output.push_str(&format!(
            "  {:?}: {{ method: {:?} }},\n",
            method.method, method.method
        ));
    }
    output.push_str("};\n");

    output.push_str(
        "export type AppServerNotificationDefinition<M extends AppServerNotificationMethod> = {\n\
           readonly method: M;\n\
           readonly __params?: NotificationParams<M>;\n\
         };\n\
         export const APP_SERVER_NOTIFICATIONS: {\n\
           [M in AppServerNotificationMethod]: AppServerNotificationDefinition<M>\n\
         } = {\n",
    );
    for notification in SERVER_NOTIFICATIONS {
        output.push_str(&format!(
            "  {:?}: {{ method: {:?} }},\n",
            notification.method, notification.method
        ));
    }
    output.push_str("};\n");
    output.push_str("export interface AppServerServerRequestMap {\n");
    for method in HOST_METHODS {
        output.push_str(&format!(
            "  {:?}: {{ params: {}; response: {} }};\n",
            method.method,
            method.params_type(),
            method.result_type()
        ));
    }
    output.push_str(
        "}\n\
         export type AppServerServerRequestMethod = keyof AppServerServerRequestMap;\n\
         export type ServerRequestParams<M extends AppServerServerRequestMethod> = AppServerServerRequestMap[M][\"params\"];\n\
         export type ServerRequestResult<M extends AppServerServerRequestMethod> = AppServerServerRequestMap[M][\"response\"];\n\
         export type AppServerServerRequest<M extends AppServerServerRequestMethod> = JsonRpcRequest<ServerRequestParams<M>> & { method: M };\n\
         export type AppServerServerResponse<M extends AppServerServerRequestMethod> = JsonRpcResponse<ServerRequestResult<M>, JsonRpcError>;\n\
         export type AppServerServerRequestDefinition<M extends AppServerServerRequestMethod> = {\n\
           readonly method: M;\n\
           readonly __params?: ServerRequestParams<M>;\n\
           readonly __result?: ServerRequestResult<M>;\n\
         };\n\
         export const APP_SERVER_SERVER_REQUESTS: { [M in AppServerServerRequestMethod]: AppServerServerRequestDefinition<M> } = {\n",
    );
    for method in HOST_METHODS {
        output.push_str(&format!(
            "  {:?}: {{ method: {:?} }},\n",
            method.method, method.method
        ));
    }
    output.push_str("};\n");
    let mut normalized = output
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n");
    normalized.push('\n');
    normalized
}

