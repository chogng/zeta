fn generated_reexport(values: &[&str], types: &[&str]) -> String {
    let values = values.join(", ");
    let types = types.join(", ");
    format!(
        "// Generated by `zeta-app-server-protocol generate_protocol`. Do not edit.\nexport {{ {values} }} from './types.js';\nexport type {{ {types} }} from './types.js';\n"
    )
}

