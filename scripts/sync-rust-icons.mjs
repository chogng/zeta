import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { basename, dirname, extname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryDirectory = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const iconDirectory = resolve(repositoryDirectory, "resources/icons");
const outputFile = resolve(repositoryDirectory, "zeterm/icons/src/generated.rs");
const iconFilePattern = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*\.svg$/;
const unsafeSvgPattern = /<(?:script|foreignObject)\b|\son[a-z]+\s*=|(?:href|xlink:href)\s*=/i;
const paintAttributePattern = /\b(?:fill|stroke)="([^"]+)"/g;
const symbolicPaints = new Set([
  "#000",
  "#000000",
  "#fff",
  "#ffffff",
  "black",
  "currentColor",
  "none",
  "white",
]);

function rustConstantName(fileName) {
  return basename(fileName, ".svg").replaceAll("-", "_").toUpperCase();
}

function renderingConstructor(svg) {
  for (const [, paint] of svg.matchAll(paintAttributePattern)) {
    if (!symbolicPaints.has(paint.toLowerCase())) {
      return "multicolor";
    }
  }
  return "symbolic";
}

function validateSvg(fileName, svg) {
  const trimmed = svg.trim();
  if (!trimmed.startsWith("<svg") || !trimmed.endsWith("</svg>")) {
    throw new Error(`Product icon '${fileName}' must contain one SVG root`);
  }
  if ((trimmed.match(/<svg\b/g) ?? []).length !== 1 || (trimmed.match(/<\/svg>/g) ?? []).length !== 1) {
    throw new Error(`Product icon '${fileName}' must contain exactly one SVG root`);
  }
  if (unsafeSvgPattern.test(trimmed)) {
    throw new Error(`Product icon '${fileName}' contains unsupported active or external content`);
  }
}

export async function syncRustIcons(options = {}) {
  const sourceDirectory = options.sourceDirectory ?? iconDirectory;
  const destination = options.outputFile ?? outputFile;
  const mode = options.mode ?? "generate";
  if (!["check", "generate"].includes(mode)) {
    throw new Error(`Unknown Rust icon mode '${mode}'`);
  }
  const files = (await readdir(sourceDirectory, { withFileTypes: true }))
    .filter((entry) => entry.isFile() && extname(entry.name) === ".svg")
    .map((entry) => entry.name)
    .sort((left, right) => {
      const leftId = basename(left, ".svg");
      const rightId = basename(right, ".svg");
      return leftId < rightId ? -1 : leftId > rightId ? 1 : 0;
    });
  if (files.length === 0) {
    throw new Error(`No product icons found in ${sourceDirectory}`);
  }

  const constants = [];
  const artwork = [];
  for (const fileName of files) {
    if (!iconFilePattern.test(fileName)) {
      throw new Error(`Invalid product icon filename '${fileName}'`);
    }
    const svg = await readFile(resolve(sourceDirectory, fileName), "utf8");
    validateSvg(fileName, svg);
    const resourceName = basename(fileName, ".svg");
    const name = rustConstantName(fileName);
    const rendering = renderingConstructor(svg);
    artwork.push({ name, resourceName });
    constants.push(
      `    pub(crate) const ${name}: IconDefinition = IconDefinition::${rendering}(include_bytes!("../../../../resources/icons/${fileName}"));`,
    );
  }

  const generated = [
    "// Generated from resources/icons by scripts/sync-rust-icons.mjs.",
    "// Do not edit this file directly.",
    "",
    "use crate::IconDefinition;",
    "",
    "// Canonical artwork can exist before a product semantic is registered.",
    "#[allow(dead_code)]",
    "#[rustfmt::skip]",
    "pub(crate) mod artwork {",
    "    use super::IconDefinition;",
    ...constants,
    "}",
    "",
    "#[cfg(test)]",
    "#[rustfmt::skip]",
    "pub(crate) const ALL_ARTWORK: &[(&str, IconDefinition)] = &[",
    ...artwork.map(({ name, resourceName }) => `    ("${resourceName}", artwork::${name}),`),
    "];",
    "",
  ].join("\n");
  if (mode === "check") {
    const current = await readFile(destination, "utf8");
    if (current !== generated) {
      throw new Error("Generated Rust product icons are stale. Run 'node scripts/sync-rust-icons.mjs'.");
    }
    return { count: files.length, outputFile: destination };
  }
  await mkdir(dirname(destination), { recursive: true });
  await writeFile(destination, generated, "utf8");
  return { count: files.length, outputFile: destination };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const argumentsSet = new Set(process.argv.slice(2));
  if ([...argumentsSet].some((argument) => argument !== "--check") || argumentsSet.size > 1) {
    throw new Error(`Expected optional --check; received ${process.argv.slice(2).join(" ")}`);
  }
  const mode = argumentsSet.has("--check") ? "check" : "generate";
  const report = await syncRustIcons({ mode });
  console.log(`${mode === "check" ? "Validated" : "Generated"} ${report.count} Rust product icon bindings.`);
}
